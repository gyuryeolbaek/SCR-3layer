#!/usr/bin/env python3
"""
reacting_spec.yaml + 확정된 유동 케이스 → scrSteadyFoam 케이스 생성 (3-2단계: 열·반응)

  03_cases/<meta.name>/
    0/          U, phi, nut (유동 케이스 최종 시간에서 복사, 고정) + T, NO, NH3, O2, H2O
    constant/   polyMesh (유동 케이스에서 복사), scrProperties
    system/     controlDict, fvSchemes, fvSolution, decomposeParDict

사용법: python3 scripts/make_reacting_case.py [reacting_spec.yaml] [--force]
"""
import argparse
import json
import pathlib
import re
import shutil
import sys

import yaml

HEADER = """/*--------------------------------*- C++ -*----------------------------------*\\
  Generated by 03_cases/scripts/make_reacting_case.py - reacting_spec.yaml을 수정할 것
\\*---------------------------------------------------------------------------*/
FoamFile
{{
    version     2.0;
    format      ascii;
    class       {cls};
    object      {obj};
}}
// * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * //

"""
M = {"NO": 30.006, "NH3": 17.031, "O2": 31.998, "H2O": 18.015, "N2": 28.013}


def v(n):
    return n["value"] if isinstance(n, dict) and "value" in n else n


def write(path, obj, body, cls="dictionary"):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(HEADER.format(cls=cls, obj=obj) + body.strip() + "\n\n// ************************************************************************* //\n")


def is_time(name):
    return re.fullmatch(r"\d+(\.\d+)?", name) is not None


def latest_time(case):
    times = [d for d in case.iterdir() if d.is_dir() and is_time(d.name) and d.name != "0"]
    return max(times, key=lambda d: float(d.name)) if times else None


def scalar_field(name, roles, internal, inlet, wall_bc, dims="[0 0 0 0 0 0 0]"):
    walls = "\n".join(f"    {w} {{ {wall_bc} }}" for w in roles["walls"])
    return f"""
dimensions      {dims};
internalField   uniform {internal:.10g};
boundaryField
{{
    {roles['inlet']}  {{ type fixedValue; value uniform {inlet:.10g}; }}
    {roles['outlet']} {{ type inletOutlet; inletValue uniform {inlet:.10g}; value uniform {inlet:.10g}; }}
{walls}
}}
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("spec", nargs="?", default="reacting_spec.yaml")
    ap.add_argument("--force", action="store_true")
    args = ap.parse_args()
    spec = yaml.safe_load(pathlib.Path(args.spec).read_text(encoding="utf-8"))

    name = spec["meta"]["name"]
    if not re.fullmatch(r"[A-Za-z][\w-]*", name):
        sys.exit("[ERROR] meta.name은 영문자로 시작해야 함")
    src = pathlib.Path(v(spec["source_flow_case"]))
    if not (src / "case_info.json").exists():
        sys.exit(f"[ERROR] 유동 케이스 없음: 03_cases/{src}/")
    fci = json.loads((src / "case_info.json").read_text(encoding="utf-8"))
    tdir = latest_time(src)
    if tdir is None:
        sys.exit(f"[ERROR] {src}/ 에 유동 결과(시간 폴더)가 없음. reconstructPar 했는지 확인")
    for f in ("U", "phi", "nut"):
        if not (tdir / f).exists():
            sys.exit(f"[ERROR] {tdir}/{f} 없음")

    geo = json.loads(pathlib.Path("../01_geometry/out/geometry_out.json").read_text(encoding="utf-8"))
    roles = geo["patch_roles"]

    case = pathlib.Path(name)
    if case.exists():
        if (latest_time(case) is not None or any(case.glob("processor*"))) and not args.force:
            sys.exit(f"[STOP] {case}/ 에 결과가 있음. 보존하려면 meta.name을 바꾸고, 덮어쓰려면 --force")
        shutil.rmtree(case)

    shutil.copytree(src / "constant" / "polyMesh", case / "constant" / "polyMesh",
                    ignore=shutil.ignore_patterns("sets"))
    (case / "0").mkdir(parents=True)
    for f in ("U", "phi", "nut"):
        shutil.copy(tdir / f, case / "0" / f)
    (case / "case.foam").touch()

    gas, cat, kin = spec["gas"], spec["catalyst"], spec["catalyst"]["kinetics"]
    X = {k: float(v(x)) for k, x in gas["inlet_mole_fraction"].items()}
    X["N2"] = 1 - sum(X.values())
    Mmix = sum(X[k] * M[k] for k in X)
    Y = {k: X[k] * M[k] / Mmix for k in X}
    Tin = fci["T_in_K"]
    Tamb = float(v(spec["wall_thermal"]["T_ambient_K"]))

    wall_T = f"type mixed; refValue uniform {Tamb}; refGradient uniform 0; valueFraction uniform 0; value uniform {Tin:.6g};"
    write(case / "0" / "T", "T", scalar_field("T", roles, Tin, Tin, wall_T, "[0 0 0 1 0 0 0]"), "volScalarField")
    for sp in ("NO", "NH3", "O2", "H2O"):
        write(case / "0" / sp, sp, scalar_field(sp, roles, Y[sp], Y[sp], "type zeroGradient;"), "volScalarField")
    # NH3*: 흡착 NH3를 나타내는 이동 가상 화학종 (입구 0)
    write(case / "0" / "NH3s", "NH3s", scalar_field("NH3s", roles, 0.0, 0.0, "type zeroGradient;"), "volScalarField")

    sc = cat["solid_conductivity"]
    model_map = {"chatterjee_coverage": "chatterjeeCoverage", "ace_pseudo_gas": "acePseudoGas"}
    kmodel = v(kin["model"])
    if kmodel not in model_map:
        sys.exit(f"[ERROR] catalyst.kinetics.model 은 {list(model_map)} 중 하나")
    if v(sc["T_unit"]) not in ("K", "C"):
        sys.exit("[ERROR] solid_conductivity.T_unit 은 K 또는 C")
    a, b = float(v(sc["a"])), float(v(sc["b"]))
    if v(sc["T_unit"]) == "C":       # lambda = a + b (T_K - 273.15)
        a = a - b * 273.15

    zones = list(fci["active_layers"])
    s = spec["solver"]
    write(case / "constant" / "scrProperties", "scrProperties", f"""
gas
{{
    rho     {fci['rho']:.8g};        // 유동 케이스와 동일 (비압축)
    cp      {float(v(gas['cp'])):.8g};
    lambdaF {float(v(gas['lambdaF'])):.8g};
    Dm      {float(v(gas['Dm'])):.8g};
    Prt     {float(v(gas['Prt'])):.6g};
    Sct     {float(v(gas['Sct'])):.6g};
    Mmix    {Mmix:.8g};
    MNO     {M['NO']}; MNH3 {M['NH3']}; MO2 {M['O2']}; MH2O {M['H2O']};
    XNOin   {X['NO']:.8g};
}}

catalyst
{{
    zones       ({' '.join(zones)});
    porosity    {fci['porosity']:.8g};
    sV          {float(v(cat['surface_to_volume'])):.8g};
    solidFraction {float(v(kin.get('solid_fraction', 1 - fci['porosity']))):.8g};
    lambdaSa    {a:.8g};      // lambda_S = a + b*T[K]
    lambdaSb    {b:.8g};
    kinetics
    {{
        model   {model_map[kmodel]};
        A1ads   {kin['R1_ads']['A']:.8g};
        A1des   {kin['R1_des']['A']:.8g};
        E1des   {kin['R1_des']['E_kJmol'] * 1e3:.8g};
        gamma   {kin['R1_des']['gamma']:.8g};
        A2      {kin['R2_oxi']['A']:.8g};
        E2      {kin['R2_oxi']['E_kJmol'] * 1e3:.8g};
        A3      {kin['R3_scr']['A']:.8g};
        E3      {kin['R3_scr']['E_kJmol'] * 1e3:.8g};
        beta    {kin['R3_scr']['beta']:.8g};
        KLH     {kin['R3_scr']['K_LH']:.8g};
        dH2     {float(v(kin['dH2_kJmol'])) * 1e3:.8g};
        dH3     {float(v(kin['dH3_kJmol'])) * 1e3:.8g};
    }}
}}

wall
{{
    patches ({' '.join(roles['walls'])});
    h       {float(v(spec['wall_thermal']['h'])):.8g};
    Tamb    {Tamb:.8g};
}}

outlet  {roles['outlet']};
pRef    101325;

convergence
{{
    residual {s['residual']};
    dEta     {s['dEta']};
    nStable  {s['n_stable']};
}}
""")

    write(case / "system" / "controlDict", "controlDict", f"""
application     {s['application']};
libs            (turbulenceModels incompressibleTurbulenceModels);   // nut 벽함수 경계 읽기용
startFrom       startTime;
startTime       0;
stopAt          endTime;
endTime         {s['max_iterations']};
deltaT          1;
writeControl    timeStep;
writeInterval   100;
purgeWrite      2;
writeFormat     binary;
writePrecision  10;
writeCompression off;
timeFormat      general;
timePrecision   6;
runTimeModifiable true;
""")
    write(case / "system" / "fvSchemes", "fvSchemes", """
ddtSchemes      { default steadyState; }
gradSchemes     { default cellLimited Gauss linear 1; }
divSchemes
{
    default         none;
    div(phi,Yi)     bounded Gauss linearUpwind grad;
    div(phi,T)      bounded Gauss linearUpwind grad;
}
laplacianSchemes { default Gauss linear limited corrected 0.5; }
interpolationSchemes { default linear; }
snGradSchemes   { default limited corrected 0.5; }
""")
    r = float(s["relaxation"])
    write(case / "system" / "fvSolution", "fvSolution", f"""
solvers
{{
    "(T|NO|NH3|NH3s|NH3tot|O2|H2O)"
    {{
        solver          PBiCGStab;
        preconditioner  DILU;
        tolerance       1e-12;
        relTol          0.01;
    }}
}}
relaxationFactors
{{
    equations {{ ".*" {r}; }}
}}
""")
    n_procs = int(v(spec["parallel"]["n_procs"]))
    write(case / "system" / "decomposeParDict", "decomposeParDict", f"numberOfSubdomains {n_procs};\nmethod scotch;\n")
    (case / "run.env").write_text(f"N_PROCS={n_procs}\nAPP={s['application']}\n")

    info = {"name": name, "revision": spec["meta"]["revision"], "stage": "reacting",
            "source_flow_case": str(src), "flow_time": tdir.name, "T_in_K": Tin, "rho": fci["rho"],
            "porosity": fci["porosity"], "active_layers": zones, "kinetics_model": kmodel, "X_in": X, "Y_in": Y, "M_mix": Mmix,
            "mass_flow_kg_s": (fci["mass_flow_kg_h_nominal"] / 3600 if "mass_flow_kg_h_nominal" in fci
                               else fci["rho"] * fci["inlet_velocity"] * fci["inlet_area"])}
    (case / "case_info.json").write_text(json.dumps(info, indent=2, ensure_ascii=False))

    print(f"[OK] 반응 케이스 생성: 03_cases/{case}/  (유동: {src}/{tdir.name})")
    print(f"     입구 {Tin - 273.15:.0f} °C, NO {X['NO'] * 1e6:.0f} ppm, NH3 {X['NH3'] * 1e6:.0f} ppm, "
          f"O2 {X['O2'] * 100:.1f} %, H2O {X['H2O'] * 100:.1f} %, M_mix {Mmix:.2f}")
    print(f"     반응 촉매층: {', '.join(zones)} / 반응 모델: {kmodel}, A_SCR {kin['R3_scr']['A']:.3g}, "
          f"E_ox {kin['R2_oxi']['E_kJmol']} kJ/mol")


if __name__ == "__main__":
    main()
