#!/usr/bin/env python3
"""
case_spec.yaml + 01_geometry/02_mesh 결과 → OpenFOAM 계산 케이스 생성 (3-1단계: 유동)

  03_cases/<meta.name>/
    0/          U p k omega nut
    constant/   polyMesh(02_mesh에서 복사), transportProperties, turbulenceProperties
    system/     controlDict(+모니터), fvSchemes, fvSolution, fvOptions(다공성), decomposeParDict
    case_info.json, run.env, case.foam

사용법: python3 scripts/make_case.py [case_spec.yaml] [--force]
"""
import argparse
import json
import math
import pathlib
import re
import shutil
import sys

import yaml

HEADER = """/*--------------------------------*- C++ -*----------------------------------*\\
  Generated by 03_cases/scripts/make_case.py - 직접 수정하지 말고 case_spec.yaml을 수정할 것
\\*---------------------------------------------------------------------------*/
FoamFile
{{
    version     2.0;
    format      ascii;
    class       {cls};
    object      {obj};
}}
// * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * //

"""
R_U = 8.314462618


def v(node):
    return node["value"] if isinstance(node, dict) and "value" in node else node


def vec(p):
    return "(" + " ".join(f"{x:.8g}" for x in p) + ")"


def write(path, obj, body, cls="dictionary"):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(HEADER.format(cls=cls, obj=obj) + body.strip() + "\n\n// ************************************************************************* //\n")


def n2_properties(T, p):
    """N2 이상기체 밀도, Sutherland 점성 (mu_ref 1.663e-5 @273.15 K, S = 107 K)"""
    M = 0.0280134
    rho = p * M / (R_U * T)
    mu = 1.663e-5 * (T / 273.15) ** 1.5 * (273.15 + 107.0) / (T + 107.0)
    return rho, mu


def has_results(case):
    return any(d.is_dir() and re.fullmatch(r"\d+(\.\d+)?", d.name) and d.name != "0" for d in case.iterdir()) \
        or any(case.glob("processor*"))


# ---------------------------------------------------------------------------
def field_U(roles, Uin):
    walls = "\n".join(f"    {w} {{ type noSlip; }}" for w in roles["walls"])
    return f"""
dimensions      [0 1 -1 0 0 0 0];
internalField   uniform (0 0 0);
boundaryField
{{
    {roles['inlet']}  {{ type fixedValue; value uniform {vec(Uin)}; }}
    {roles['outlet']} {{ type inletOutlet; inletValue uniform (0 0 0); value uniform (0 0 0); }}
{walls}
}}
"""


def field_p(roles):
    walls = "\n".join(f"    {w} {{ type zeroGradient; }}" for w in roles["walls"])
    return f"""
dimensions      [0 2 -2 0 0 0 0];
internalField   uniform 0;
boundaryField
{{
    {roles['inlet']}  {{ type zeroGradient; }}
    {roles['outlet']} {{ type fixedValue; value uniform 0; }}
{walls}
}}
"""


def field_turb(roles, name, dims, val, wall_type):
    walls = "\n".join(f"    {w} {{ type {wall_type}; value uniform {val:.6g}; }}" for w in roles["walls"])
    return f"""
dimensions      {dims};
internalField   uniform {val:.6g};
boundaryField
{{
    {roles['inlet']}  {{ type fixedValue; value uniform {val:.6g}; }}
    {roles['outlet']} {{ type inletOutlet; inletValue uniform {val:.6g}; value uniform {val:.6g}; }}
{walls}
}}
"""


def field_nut(roles):
    walls = "\n".join(f"    {w} {{ type nutkWallFunction; value uniform 0; }}" for w in roles["walls"])
    return f"""
dimensions      [0 2 -1 0 0 0 0];
internalField   uniform 0;
boundaryField
{{
    {roles['inlet']}  {{ type calculated; value uniform 0; }}
    {roles['outlet']} {{ type calculated; value uniform 0; }}
{walls}
}}
"""


def fv_options(spec, active):
    cat = spec["catalyst"]
    k = float(v(cat["permeability_k"]))
    cF = float(v(cat["drag_cF"]))
    tf = float(v(cat["transverse_factor"]))
    d_ax, f_ax = 1.0 / k, 2.0 * cF / math.sqrt(k)
    ax = [float(x) for x in cat["axial_direction"]]
    # 축 방향이 z가 아닐 때를 위해 국소 좌표계 사용: e3 = 축
    e1 = [1.0, 0.0, 0.0] if abs(ax[0]) < 0.9 else [0.0, 1.0, 0.0]
    # e1을 축에 수직하게 만들기
    dot = sum(a * b for a, b in zip(e1, ax))
    e1 = [a - dot * b for a, b in zip(e1, ax)]
    n = math.sqrt(sum(a * a for a in e1)); e1 = [a / n for a in e1]
    e2 = [ax[1] * e1[2] - ax[2] * e1[1], ax[2] * e1[0] - ax[0] * e1[2], ax[0] * e1[1] - ax[1] * e1[0]]

    blocks, porous_blocks = [], []
    for z in active:
        # porousSimpleFoam의 constant/porosityProperties: 비등방 텐서를 압력식에서 암시적으로 처리
        porous_blocks.append(f"""
{z}
{{
    type            DarcyForchheimer;
    cellZone        {z};
    d   ({d_ax * tf:.6e} {d_ax * tf:.6e} {d_ax:.6e});
    f   ({f_ax * tf:.6e} {f_ax * tf:.6e} {f_ax:.6e});
    coordinateSystem
    {{
        origin  (0 0 0);
        e1      {vec(e1)};
        e2      {vec(e2)};
    }}
}}""")
        if spec["turbulence"].get("laminarize_porous", False):
            blocks.append(f"""
{z}_laminar
{{
    type            scalarFixedValueConstraint;
    selectionMode   cellZone;
    cellZone        {z};
    fieldValues
    {{
        k       1e-8;
    }}
}}""")
    return "\n".join(blocks), "\n".join(porous_blocks), {"d_axial": d_ax, "f_axial": f_ax, "d_transverse": d_ax * tf, "f_transverse": f_ax * tf,
                               "e1": e1, "e2": e2}


def monitor_planes(info, active, h):
    """각 활성 촉매층 위/아래 평면 (격자면과 겹치지 않게 0.4h 띄움)"""
    planes = {}
    for c in info["catalyst_zones"]:
        if c["name"] in active:
            planes[f"{c['name']}_in"] = c["z_max"] + 0.4 * h
            planes[f"{c['name']}_out"] = c["z_min"] - 0.4 * h
    return planes


def control_dict(spec, roles, planes):
    s = spec["solver"]
    res_fields = "yes" if s.get("write_residual_fields", False) else "no"
    fos = [f"""
    solverInfo {{ type solverInfo; libs (utilityFunctionObjects); fields (U p k omega); writeResidualFields {res_fields}; }}"""]
    fa = s.get("field_average", {}) or {}
    if fa.get("enabled", False):
        t0 = max(int(s["max_iterations"]) - int(fa["window"]), 0)
        flds = "\n".join(f"            {f} {{ mean on; prime2Mean off; base iteration; }}" for f in fa.get("fields", ["U", "p"]))
        fos.append(f"""
    fieldAverage1
    {{
        type            fieldAverage;
        libs            (fieldFunctionObjects);
        writeControl    writeTime;
        timeStart       {t0};       // 마지막 {fa['window']}회 평균 (max_iterations - window)
        restartOnRestart false;
        fields
        (
{flds}
        );
    }}""")
    fos.append(f"""
    yPlus {{ type yPlus; libs (fieldFunctionObjects); writeControl writeTime; }}
    massFlow_inlet  {{ type surfaceFieldValue; libs (fieldFunctionObjects); log false; writeFields false;
                      regionType patch; name {roles['inlet']};  operation sum; fields (phi); }}
    massFlow_outlet {{ type surfaceFieldValue; libs (fieldFunctionObjects); log false; writeFields false;
                      regionType patch; name {roles['outlet']}; operation sum; fields (phi); }}
    p_inlet  {{ type surfaceFieldValue; libs (fieldFunctionObjects); log false; writeFields false;
               regionType patch; name {roles['inlet']};  operation areaAverage; fields (p); }}
    p_outlet {{ type surfaceFieldValue; libs (fieldFunctionObjects); log false; writeFields false;
               regionType patch; name {roles['outlet']}; operation areaAverage; fields (p); }}""")
    for tag, z in planes.items():
        fos.append(f"""
    p_{tag}
    {{
        type surfaceFieldValue; libs (fieldFunctionObjects); log false; writeFields false;
        regionType sampledSurface;
        name plane_{tag};
        sampledSurfaceDict
        {{
            type        cuttingPlane;
            planeType   pointAndNormal;
            pointAndNormalDict {{ point (0 0 {z:.6g}); normal (0 0 1); }}
            interpolate false;
        }}
        operation areaAverage;
        fields (p);
    }}""")
    return f"""
application     {s['application']};
startFrom       latestTime;
startTime       0;
stopAt          endTime;
endTime         {s['max_iterations']};
deltaT          1;
writeControl    timeStep;
writeInterval   {s['write_interval']};
purgeWrite      2;
writeFormat     binary;
writePrecision  8;
writeCompression off;
timeFormat      general;
timePrecision   6;
runTimeModifiable true;

functions
{{
{''.join(fos)}
}}
"""


SCHEMES = """
ddtSchemes      { default steadyState; }
gradSchemes
{
    default         Gauss linear;
    grad(U)         cellLimited Gauss linear 1;
}
divSchemes
{
    default         none;
    div(phi,U)      bounded Gauss linearUpwind grad(U);
    div(phi,k)      bounded Gauss upwind;
    div(phi,omega)  bounded Gauss upwind;
    div((nuEff*dev2(T(grad(U))))) Gauss linear;
}
laplacianSchemes { default Gauss linear limited corrected 0.5; }
interpolationSchemes { default linear; }
snGradSchemes   { default limited corrected 0.5; }
wallDist        { method meshWave; }
"""


def fv_solution(spec):
    r = spec["solver"]["residual_target"]
    return f"""
solvers
{{
    p
    {{
        solver          GAMG;
        smoother        GaussSeidel;
        tolerance       1e-8;
        relTol          0.05;
    }}
    "(U|k|omega)"
    {{
        solver          smoothSolver;
        smoother        symGaussSeidel;
        tolerance       1e-9;
        relTol          0.1;
    }}
}}

SIMPLE
{{
    nUCorrectors    2;
    nNonOrthogonalCorrectors 1;
    consistent      no;
    residualControl
    {{
        p               {r};
        U               {r};
        "(k|omega)"     {r};
    }}
}}

relaxationFactors
{{
    fields      {{ p 0.3; }}
    equations   {{ U 0.7; k 0.7; omega 0.7; }}
}}
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("spec", nargs="?", default="case_spec.yaml")
    ap.add_argument("--force", action="store_true", help="기존 결과가 있어도 덮어쓰기")
    args = ap.parse_args()

    spec = yaml.safe_load(pathlib.Path(args.spec).read_text(encoding="utf-8"))
    if spec["meta"]["stage"] != "flow":
        sys.exit("[STOP] stage: reacting 은 아직 구현되지 않음 (3-2단계)")
    name = spec["meta"]["name"]
    if not re.fullmatch(r"[A-Za-z][\w-]*", name):
        sys.exit("[ERROR] meta.name은 영문자로 시작해야 함 (숫자로 시작하면 git이 시간 폴더로 오인)")

    mdir = pathlib.Path(spec["mesh"]["dir"])
    mesh_spec = yaml.safe_load((mdir / "mesh_spec.yaml").read_text(encoding="utf-8"))
    gdir = (mdir / mesh_spec["input"]["geometry_dir"]).resolve()
    info = json.loads((gdir / mesh_spec["input"]["info"]).read_text(encoding="utf-8"))
    h = float(v(mesh_spec["background"]["cell_size"]))
    poly = mdir / "case" / "constant" / "polyMesh"
    if not (poly / "owner").exists():
        sys.exit(f"[ERROR] 격자 없음: {poly} → 02_mesh/Allmesh 실행 필요")

    case = pathlib.Path(name)
    if case.exists():
        if has_results(case) and not args.force:
            sys.exit(f"[STOP] {case}/ 에 계산 결과가 있음. 보존하려면 meta.name을 바꾸고, 덮어쓰려면 --force")
        shutil.rmtree(case)

    roles = info["patch_roles"]
    zones = [c["name"] for c in info["catalyst_zones"]]
    active = list(v(spec["catalyst"]["active_layers"]))
    bad = [z for z in active if z not in zones]
    if bad:
        sys.exit(f"[ERROR] 격자에 없는 cellZone: {bad} (있는 것: {zones})")

    T = float(v(spec["operating"]["inlet_temperature_C"])) + 273.15
    p_amb = float(v(spec["operating"]["ambient_pressure"]))
    rho, mu = n2_properties(T, p_amb)
    nu = mu / rho
    Vin = float(v(spec["operating"]["inlet_velocity"]))
    Din = info["inlet"]["diameter"]
    A_in = math.pi * Din ** 2 / 4
    turb = spec["turbulence"]
    k_in = 1.5 * (turb["inlet_intensity"] * Vin) ** 2
    L = turb["inlet_mixing_length_ratio"] * Din
    om_in = math.sqrt(k_in) / (0.09 ** 0.25 * L)

    shutil.copytree(poly, case / "constant" / "polyMesh",
                    ignore=shutil.ignore_patterns("sets"))
    (case / "case.foam").touch()

    write(case / "0" / "U", "U", field_U(roles, [0, 0, -Vin]), "volVectorField")
    write(case / "0" / "p", "p", field_p(roles), "volScalarField")
    write(case / "0" / "k", "k", field_turb(roles, "k", "[0 2 -2 0 0 0 0]", k_in, "kqRWallFunction"), "volScalarField")
    write(case / "0" / "omega", "omega", field_turb(roles, "omega", "[0 0 -1 0 0 0 0]", om_in, "omegaWallFunction"), "volScalarField")
    write(case / "0" / "nut", "nut", field_nut(roles), "volScalarField")

    write(case / "constant" / "transportProperties", "transportProperties",
          f"transportModel  Newtonian;\nnu              {nu:.6e};   // N2 @ {T:.2f} K (mu {mu:.4e} Pa s, rho {rho:.4f} kg/m3)\n")
    write(case / "constant" / "turbulenceProperties", "turbulenceProperties",
          f"simulationType  RAS;\nRAS\n{{\n    RASModel        {v(turb['model'])};\n    turbulence      on;\n    printCoeffs     on;\n}}\n")

    opts, porosity, porous = fv_options(spec, active)
    planes = monitor_planes(info, active, h)
    write(case / "constant" / "porosityProperties", "porosityProperties", porosity)
    write(case / "system" / "fvOptions", "fvOptions", opts)
    write(case / "system" / "controlDict", "controlDict", control_dict(spec, roles, planes))
    write(case / "system" / "fvSchemes", "fvSchemes", SCHEMES)
    write(case / "system" / "fvSolution", "fvSolution", fv_solution(spec))
    n_procs = int(v(spec["parallel"]["n_procs"]))
    write(case / "system" / "decomposeParDict", "decomposeParDict", f"numberOfSubdomains {n_procs};\nmethod scotch;\n")

    case_info = {
        "name": name, "revision": spec["meta"]["revision"], "stage": "flow",
        "T_in_K": T, "rho": rho, "mu": mu, "nu": nu,
        "inlet_velocity": Vin, "inlet_diameter": Din, "inlet_area": A_in,
        "mass_flow_kg_h_nominal": rho * Vin * A_in * 3600,
        "k_in": k_in, "omega_in": om_in,
        "active_layers": active, "porosity": float(v(spec["catalyst"]["porosity"])),
        "porous_coeffs": porous, "monitor_planes": planes, "cell_size": h,
        "write_residual_fields": bool(spec["solver"].get("write_residual_fields", False)),
        "field_average": spec["solver"].get("field_average") or {"enabled": False},
    }
    if case_info["field_average"].get("enabled"):
        case_info["field_average"]["time_start"] = max(
            int(spec["solver"]["max_iterations"]) - int(case_info["field_average"]["window"]), 0)
    (case / "case_info.json").write_text(json.dumps(case_info, indent=2, ensure_ascii=False))
    (case / "run.env").write_text(f"N_PROCS={n_procs}\nAPP={spec['solver']['application']}\n")

    print(f"[OK] 케이스 생성: 03_cases/{case}/")
    print(f"     N2 @ {T - 273.15:.0f} °C: rho {rho:.4f} kg/m3, mu {mu:.3e} Pa s, nu {nu:.3e} m2/s")
    print(f"     입구 {Vin} m/s × D {Din} m → 질량유량 {case_info['mass_flow_kg_h_nominal']:.0f} kg/h")
    print(f"     다공성 (축/가로): d {porous['d_axial']:.3e}/{porous['d_transverse']:.3e} 1/m2, "
          f"f {porous['f_axial']:.3f}/{porous['f_transverse']:.3e} 1/m")
    print(f"     활성 촉매층: {', '.join(active)}")


if __name__ == "__main__":
    main()
