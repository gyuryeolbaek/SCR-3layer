#!/usr/bin/env python3
"""
mesh_spec.yaml + 01_geometry/out/geometry_out.json → OpenFOAM 격자 케이스(case/) 생성

생성물 (case/):
  system/  blockMeshDict, surfaceFeatureExtractDict, snappyHexMeshDict(.layers),
           topoSetDict, decomposeParDict, controlDict, fvSchemes, fvSolution
  constant/triSurface/fluid.stl
  case.foam, mesh_run.env (Allmesh가 읽는 실행 옵션)

사용법: python3 scripts/make_mesh_case.py [mesh_spec.yaml] [--case case]
"""
import argparse
import json
import math
import pathlib
import shutil
import sys

import yaml

HEADER = """/*--------------------------------*- C++ -*----------------------------------*\\
  Generated by 02_mesh/scripts/make_mesh_case.py - 직접 수정하지 말고 mesh_spec.yaml을 수정할 것
\\*---------------------------------------------------------------------------*/
FoamFile
{{
    version     2.0;
    format      ascii;
    class       dictionary;
    object      {obj};
}}
// * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * //

"""


def v(node):
    return node["value"] if isinstance(node, dict) and "value" in node else node


def vec(p):
    return "(" + " ".join(f"{x:.6g}" for x in p) + ")"


def write(path, obj, body):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(HEADER.format(obj=obj) + body.strip() + "\n\n// ************************************************************************* //\n")


# ---------------------------------------------------------------------------
def background_box(info, h, margin):
    """형상 bbox를 감싸는 배경 격자. 경계를 h의 배수에 맞춰 촉매층 z면과 격자면을 정렬"""
    lo, hi = info["bbox"]["min"], info["bbox"]["max"]
    bmin = [round((math.floor(lo[k] / h + 1e-9) - margin) * h, 9) for k in range(3)]
    bmax = [round((math.ceil(hi[k] / h - 1e-9) + margin) * h, 9) for k in range(3)]
    n = [int(round((bmax[k] - bmin[k]) / h)) for k in range(3)]
    return bmin, bmax, n


def check_alignment(info, h):
    """촉매층 경계 z가 배경 격자면(h 배수)에 놓이는지"""
    bad = []
    for c in info["catalyst_zones"]:
        for z in (c["z_min"], c["z_max"]):
            if abs(z / h - round(z / h)) > 1e-6:
                bad.append(f"{c['name']} z={z}")
    return bad


def block_mesh_dict(bmin, bmax, n):
    x0, y0, z0 = bmin
    x1, y1, z1 = bmax
    verts = [(x0, y0, z0), (x1, y0, z0), (x1, y1, z0), (x0, y1, z0),
             (x0, y0, z1), (x1, y0, z1), (x1, y1, z1), (x0, y1, z1)]
    vs = "\n".join(f"    {vec(p)}" for p in verts)
    return f"""
scale 1;

vertices
(
{vs}
);

blocks
(
    hex (0 1 2 3 4 5 6 7) ({n[0]} {n[1]} {n[2]}) simpleGrading (1 1 1)
);

edges ();

boundary
(
    background
    {{
        type patch;
        faces
        (
            (3 7 6 2) (0 4 7 3) (2 6 5 1) (1 5 4 0) (0 3 2 1) (4 5 6 7)
        );
    }}
);
"""


def feature_dict(ref):
    return f"""
fluid.stl
{{
    extractionMethod    extractFromSurface;
    extractFromSurfaceCoeffs
    {{
        includedAngle   {ref['feature_angle']};
    }}
    subsetFeatures
    {{
        nonManifoldEdges    no;
        openEdges           yes;
    }}
    writeObj            yes;
}}
"""


def snappy_dict(info, spec, stage):
    ref, lay, q = spec["refinement"], spec["layers"], spec["quality"]
    roles = info["patch_roles"]
    walls = roles["walls"]
    all_patches = [roles["inlet"], roles["outlet"], *walls]

    regions_geom = "\n".join(f"            {p} {{ name {p}; }}" for p in all_patches)

    def lvl(p):
        if p in ref.get("per_patch", {}):
            return ref["per_patch"][p]
        return ref["inlet_outlet"] if p in (roles["inlet"], roles["outlet"]) else ref["default_wall"]

    reg_ref = "\n".join(
        f"                {p} {{ level ({lvl(p)[0]} {lvl(p)[1]}); patchInfo {{ type {'wall' if p in walls else 'patch'}; }} }}"
        for p in all_patches)
    min_lvl = min(lvl(p)[0] for p in all_patches)
    max_lvl = max(lvl(p)[1] for p in all_patches)

    cat_lvl = int(ref.get("catalyst_level", 0))
    W, D = info["housing"]["W"], info["housing"]["D"]
    boxes = "\n".join(
        f"    {c['name']}_box {{ type searchableBox; min {vec(c['box_min'])}; max {vec(c['box_max'])}; }}"
        for c in info["catalyst_zones"]) if cat_lvl > 0 else ""
    regions_ref = "\n".join(
        f"        {c['name']}_box {{ mode inside; levels ((1e15 {cat_lvl})); }}"
        for c in info["catalyst_zones"]) if cat_lvl > 0 else ""

    layer_pat = "\n".join(f"        {p} {{ nSurfaceLayers {v(lay['n_layers'])}; }}" for p in walls)

    switches = {"mesh": ("true", "true", "false"), "layers": ("false", "false", "true")}[stage]

    return f"""
castellatedMesh {switches[0]};
snap            {switches[1]};
addLayers       {switches[2]};

geometry
{{
    fluid.stl
    {{
        type triSurfaceMesh;
        name fluid;
        regions
        {{
{regions_geom}
        }}
    }}
{boxes}
}}

castellatedMeshControls
{{
    maxLocalCells       {q['max_cells']};
    maxGlobalCells      {q['max_cells']};
    minRefinementCells  10;
    maxLoadUnbalance    0.10;
    nCellsBetweenLevels {ref['n_cells_between_levels']};

    features
    (
        {{ file "fluid.eMesh"; level {ref['feature_level']}; }}
    );

    refinementSurfaces
    {{
        fluid
        {{
            level ({min_lvl} {max_lvl});
            regions
            {{
{reg_ref}
            }}
        }}
    }}

    resolveFeatureAngle {ref['resolve_feature_angle']};

    refinementRegions
    {{
{regions_ref}
    }}

    locationInMesh {vec(info['location_in_mesh'])};
    allowFreeStandingZoneFaces true;
}}

snapControls
{{
    nSmoothPatch            3;
    tolerance               2.0;
    nSolveIter              50;
    nRelaxIter              5;
    nFeatureSnapIter        10;
    implicitFeatureSnap     false;
    explicitFeatureSnap     true;
    multiRegionFeatureSnap  false;
}}

addLayersControls
{{
    relativeSizes           true;
    layers
    {{
{layer_pat}
    }}
    expansionRatio          {lay['expansion_ratio']};
    finalLayerThickness     {lay['final_layer_thickness']};
    minThickness            {lay['min_thickness']};
    nGrow                   0;
    featureAngle            130;
    slipFeatureAngle        30;
    nRelaxIter              3;
    nSmoothSurfaceNormals   1;
    nSmoothNormals          3;
    nSmoothThickness        10;
    maxFaceThicknessRatio   0.5;
    maxThicknessToMedialRatio 0.3;
    minMedialAxisAngle      90;
    nBufferCellsNoExtrude   0;
    nLayerIter              50;
}}

meshQualityControls
{{
    maxNonOrtho             {q['max_non_ortho']};
    maxBoundarySkewness     20;
    maxInternalSkewness     {q['max_skewness']};
    maxConcave              80;
    minVol                  1e-13;
    minTetQuality           1e-15;
    minArea                 -1;
    minTwist                0.02;
    minDeterminant          0.001;
    minFaceWeight           0.05;
    minVolRatio             0.01;
    minTriangleTwist        -1;
    nSmoothScale            4;
    errorReduction          0.75;
    relaxed
    {{
        maxNonOrtho         75;
    }}
}}

mergeTolerance 1e-6;
"""


def topo_set_dict(info, h):
    acts = []
    for c in info["catalyst_zones"]:
        lo = [c["box_min"][0] - h, c["box_min"][1] - h, c["box_min"][2]]
        hi = [c["box_max"][0] + h, c["box_max"][1] + h, c["box_max"][2]]
        acts.append(f"""    {{
        name    {c['name']};
        type    cellZoneSet;
        action  new;
        source  boxToCell;
        box     {vec(lo)} {vec(hi)};
    }}""")
    return "actions\n(\n" + "\n".join(acts) + "\n);\n"


CONTROL = """
application     snappyHexMesh;
startFrom       latestTime;
startTime       0;
stopAt          endTime;
endTime         0;
deltaT          1;
writeControl    timeStep;
writeInterval   1;
writeFormat     ascii;
writePrecision  10;
writeCompression off;
timeFormat      general;
timePrecision   6;
runTimeModifiable false;
"""

SCHEMES = """
ddtSchemes      { default steadyState; }
gradSchemes     { default Gauss linear; }
divSchemes      { default none; }
laplacianSchemes { default Gauss linear corrected; }
interpolationSchemes { default linear; }
snGradSchemes   { default corrected; }
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("spec", nargs="?", default="mesh_spec.yaml")
    ap.add_argument("--case", default="case")
    args = ap.parse_args()

    spec = yaml.safe_load(pathlib.Path(args.spec).read_text(encoding="utf-8"))
    gdir = pathlib.Path(spec["input"]["geometry_dir"])
    info = json.loads((gdir / spec["input"]["info"]).read_text(encoding="utf-8"))
    stl = gdir / spec["input"]["stl"]
    if not stl.exists():
        sys.exit(f"[ERROR] STL 없음: {stl}")

    h = float(v(spec["background"]["cell_size"]))
    bad = check_alignment(info, h)
    if bad:
        print("[WARN] 촉매층 경계가 배경 격자면과 맞지 않음 → 촉매층 두께가 최대 1셀 어긋날 수 있음:", ", ".join(bad))

    bmin, bmax, n = background_box(info, h, int(spec["background"].get("margin_cells", 1)))
    n_bg = n[0] * n[1] * n[2]

    case = pathlib.Path(args.case)
    if case.exists():
        shutil.rmtree(case)
    (case / "constant" / "triSurface").mkdir(parents=True)
    shutil.copy(stl, case / "constant" / "triSurface" / "fluid.stl")
    (case / "case.foam").touch()

    sysd = case / "system"
    write(sysd / "controlDict", "controlDict", CONTROL)
    write(sysd / "fvSchemes", "fvSchemes", SCHEMES)
    write(sysd / "fvSolution", "fvSolution", "")
    write(sysd / "blockMeshDict", "blockMeshDict", block_mesh_dict(bmin, bmax, n))
    write(sysd / "surfaceFeatureExtractDict", "surfaceFeatureExtractDict", feature_dict(spec["refinement"]))
    write(sysd / "snappyHexMeshDict", "snappyHexMeshDict", snappy_dict(info, spec, "mesh"))
    write(sysd / "snappyHexMeshDict.layers", "snappyHexMeshDict", snappy_dict(info, spec, "layers"))
    write(sysd / "topoSetDict", "topoSetDict", topo_set_dict(info, h))
    n_procs = int(spec["parallel"]["n_procs"])
    write(sysd / "decomposeParDict", "decomposeParDict",
          f"numberOfSubdomains {n_procs};\nmethod scotch;\n")

    (case / "mesh_run.env").write_text(
        f"N_PROCS={n_procs}\nLAYERS={'1' if spec['layers']['enabled'] else '0'}\n")

    meta = {"background": {"min": bmin, "max": bmax, "n": n, "cells": n_bg, "cell_size": h},
            "alignment_warnings": bad}
    (case / "mesh_case.json").write_text(json.dumps(meta, indent=2, ensure_ascii=False))

    print(f"[OK] 케이스 생성: {case}/")
    print(f"     배경 격자 {n[0]}x{n[1]}x{n[2]} = {n_bg:,} cells (h = {h} m)")
    print(f"     locationInMesh {info['location_in_mesh']}")


if __name__ == "__main__":
    main()
